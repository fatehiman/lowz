    /**
     * Build a Persian-native slug: keep Persian letters/digits, turn spaces
     * into dashes, and strip characters that break URLs. Intentionally does
     * NOT use Str::slug(), which strips non-ASCII characters.
     */
    private function persianSlug(string $title): string
    {
        $clean = str_replace(['؟', '!', '،', '.', ':', '«', '»', '"', "'", '؛'], '', trim($title));
        $clean = preg_replace('/\s+/u', '-', $clean);

        return trim($clean, '-');
    }

    public function run(): void
    {
        $categories = ArticleCategory::query()->pluck('id', 'slug');

        foreach ($this->articles() as $data) {
            Article::query()->firstOrCreate(['slug' => $this->persianSlug($data['title'])], [
                'article_category_id' => $categories[$data['category']] ?? null,
                'title' => $data['title'],
                'excerpt' => $data['excerpt'],
                'meta_description' => $data['excerpt'],
                'keywords' => $data['keywords'],
                'body' => $data['body'],
                'image' => $data['image'],
                'image_alt' => $data['image_alt'],
                'is_published' => true,
                'published_at' => Carbon::now()->subDays($data['daysAgo']),
            ]);
        }
    }

